import type { Vector3 } from 'three'

export type QualityTier = 'low' | 'medium' | 'high'

/** Что именно на первом экране сейчас под курсором. */
export type HeroCtaTarget = 'cases' | 'contact' | null

/**
 * Состояние кадра. Все величины — демпфированные скаляры 0…1, а не флаги:
 * шейдеры смешивают их между собой, поэтому переходы получаются непрерывными
 * и отдельных сцен на каждое состояние не нужно.
 */
export type HeroFrame = {
  /** Секунды с запуска сцены. */
  time: number
  /** Секунды с прошлого кадра, ограничены сверху — вкладка могла быть скрыта. */
  delta: number
  /** Прогресс вступления, 0 → 1 за ~2.2 с. Назад не откатывается. */
  reveal: number
  /** Положение указателя в нормализованных координатах, со сглаживанием. */
  pointer: { x: number; y: number }
  /** Направление на указатель в пространстве сцены — для локальной волны. */
  pointerWorld: Vector3
  /** Свежесть движения указателя: 1 сразу после движения, затухает за ~0.6 с. */
  interaction: number
  /** Прогресс ухода первого экрана вверх, 0…1. */
  scroll: number
  /** Вес наведения на «Смотреть кейсы». */
  cases: number
  /** Вес наведения на «Обсудить проект». */
  contact: number
  /** Импульс сигнальной сетки: выставляется в 1 на событии, гаснет за ~1.2 с. */
  gridPulse: number
  /** Фаза бегущей сигнальной линии, 0…1. */
  signalPhase: number
  reducedMotion: boolean
  /** Мобильная раскладка: объект выше и мельче, реакции на указатель нет. */
  compact: boolean
}

/** Общий контракт объектов сцены — оркестратор не знает их внутренностей. */
export type HeroObject = {
  update(frame: HeroFrame): void
  dispose(): void
}
